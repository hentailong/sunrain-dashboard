"""Dengta's public App webcasts board, verified against Android 8.3.2.

The official H5 SDK uses an anonymous _m_h5_tk cookie and an MD5 request
checksum. No account token, corporate registration, or phone is required.
Only v3.0's beaconmarketshare_play_vv board represents the metrics below;
the legacy v2.1 beacon board can return old data with a successful status.
"""
from __future__ import annotations

import hashlib
import json
import math
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path

import httpx

from backend.dramas import DRAMAS, PRIMARY
from backend.dengta_minutes import nearest_minute

TZ = timezone(timedelta(hours=8))
PAGE = 'https://dengtapro.taopiaopiao.com/webcasts.html?pageRadiusColor=4884ff'
API = 'mtop.alipictures.gravitywave.media.rank.list'
VERSION = '3.0'
ENDPOINT = f'https://acs.m.taopiaopiao.com/h5/{API}/{VERSION}/'
APP_KEY = '12574478'
EVIDENCE = Path(__file__).resolve().parent / 'evidence'


def parameters(current: datetime) -> dict:
    return {'configCode': '1', 'typeCode': '12', 'platformCode': 'beaconmarketshare_play_vv',
            'showDate': current.astimezone(TZ).strftime('%Y%m%d'), 'dateType': '0', 'isLoop': False}


def number(value):
    if isinstance(value, bool):
        return None
    try:
        result = float(value)
    except (TypeError, ValueError):
        return None
    return result if math.isfinite(result) else None


def board(payload, requested_date):
    if not isinstance(payload, dict) or not any(str(r).startswith('SUCCESS::') for r in payload.get('ret', [])):
        return None
    envelope = payload.get('data')
    if not isinstance(envelope, dict) or str(envelope.get('code')) != '200':
        return None
    data = envelope.get('data')
    if not isinstance(data, dict):
        return None
    calendar = data.get('calendarMap')
    ranks = data.get('rankMap')
    if not isinstance(calendar, dict) or calendar.get('showDate') != requested_date or not isinstance(ranks, dict):
        return None
    title = ranks.get('titleInfo', {})
    if not isinstance(title, dict) or title.get('columnName1') != '实时正片播放量':
        return None
    rows = ranks.get('rankList')
    return rows if isinstance(rows, list) else None


def parse_payload(payload, title_name=PRIMARY, *, current=None):
    current = (current or datetime.now(TZ)).astimezone(TZ)
    day = current.strftime('%Y%m%d')
    rows = board(payload, day)
    if rows is None:
        return []
    matches = [row for row in rows if isinstance(row, dict) and row.get('mediaName') == title_name]
    if len(matches) != 1:
        return []
    row = matches[0]
    count, share, rank = (number(row.get(key)) for key in ('vvCnt', 'cnt', 'mediaRank'))
    displayed_share = number(row.get('columnValue1'))
    if (count is None or count < 0 or count != int(count) or share is None or not 0 <= share <= 1
            or rank is None or rank < 0 or rank != int(rank) or displayed_share is None
            or abs(displayed_share - share * 100) > 0.02):
        return []
    try:
        stamp = datetime.strptime(row['modifiedTime'], '%Y-%m-%d %H:%M:%S').replace(tzinfo=TZ)
    except (KeyError, TypeError, ValueError):
        return []
    if stamp.strftime('%Y%m%d') != day or not -300 <= (current - stamp).total_seconds() <= 7200:
        return []
    meta = {'scope': '灯塔网播 · 全部剧集 · 当日正片播放', 'method': 'official_api',
            'frequency': 'intraday', 'statistical_date': current.date().isoformat(),
            'sample_minute': nearest_minute(current.isoformat()), 'request_started_at': current.isoformat(),
            'resets_daily': True, 'title': title_name, 'media_id': row.get('mediaId'),
            'sample_size': len(rows), 'official_url': ENDPOINT, 'official_page': PAGE,
            'api_version': VERSION, 'platform_code': 'beaconmarketshare_play_vv',
            'meaning': '灯塔正片播放口径；不等同于云合正片有效播放。当天累计，跨日重新统计。'}
    return [{'metric': metric, 'value': value, 'unit': unit, 'source_time': stamp.isoformat(),
             'source_url': PAGE, 'metadata': dict(meta, field=field)}
            for metric, value, unit, field in [
                ('dengta_play_count', count, '次', 'vvCnt'),
                ('dengta_play_share', share * 100, '%', 'cnt * 100'),
                ('dengta_play_rank', rank + 1, '名', 'mediaRank + 1')]]


async def request_board(client: httpx.AsyncClient, params: dict, *, api=API, version=VERSION) -> dict:
    data = json.dumps(params, ensure_ascii=False, separators=(',', ':'))
    for attempt in range(2):
        # The anonymous token is generated by the server, stays in this client,
        # and is never written into evidence or source links.
        token = next((c.value.split('_')[0] for c in client.cookies.jar if c.name == '_m_h5_tk'), '')
        stamp = str(int(time.time() * 1000))
        checksum = hashlib.md5(f'{token}&{stamp}&{APP_KEY}&{data}'.encode()).hexdigest()
        response = await client.get(f'https://acs.m.taopiaopiao.com/h5/{api}/{version}/', params={
            'jsv': '2.7.4', 'appKey': APP_KEY, 't': stamp, 'sign': checksum,
            'api': api, 'v': version, 'type': 'originaljson', 'dataType': 'json', 'data': data})
        response.raise_for_status()
        payload = response.json()
        if not isinstance(payload, dict):
            raise ValueError('Unexpected JSON structure')
        statuses = payload.get('ret', [])
        if attempt == 0 and any(str(r).split('::')[0] in
                ('FAIL_SYS_TOKEN_EMPTY', 'FAIL_SYS_TOKEN_EXOIRED', 'FAIL_SYS_TOKEN_EXPIRED') for r in statuses):
            continue
        return payload
    return payload


def save_evidence(payload, params, captured_at):
    data = payload['data']['data']
    fields = ('mediaId', 'mediaName', 'mediaRank', 'vvCnt', 'cnt', 'columnValue1',
              'modifiedTime', 'platformCode', 'vvCntWithUnit')
    content = json.dumps({
        'official_url': ENDPOINT, 'official_page': PAGE, 'api_version': VERSION,
        'parameters': params, 'captured_at': captured_at.isoformat(),
        'note': '官方网播榜字段摘录；vvCnt为当日正片播放次数，cnt乘100为市占百分比，mediaRank从0起。未包含登录或匿名会话凭据。',
        'response': {'ret': payload.get('ret'), 'data': {'code': payload['data']['code'],
            'data': {'calendarMap': data['calendarMap'], 'rankMap': {
                'titleInfo': data['rankMap']['titleInfo'],
                'rankList': [{key: row[key] for key in fields if key in row}
                             for row in data['rankMap']['rankList'] if isinstance(row, dict)]}}}}},
        ensure_ascii=False, indent=2)
    filename = hashlib.sha256(content.encode()).hexdigest() + '.json'
    EVIDENCE.mkdir(exist_ok=True)
    (EVIDENCE / filename).write_text(content, encoding='utf-8')
    return 'http://127.0.0.1:8000/api/evidence/' + filename


async def collect_dengta_api():
    current = datetime.now(TZ)
    params = parameters(current)

    def failure(state, message):
        return {title: {'state': state, 'message': message, 'readings': []} for title in DRAMAS}

    try:
        async with httpx.AsyncClient(timeout=20, follow_redirects=False, headers={
                'Referer': PAGE, 'Accept': 'application/json', 'User-Agent': 'Mozilla/5.0'}) as client:
            payload = await request_board(client, params)
    except httpx.HTTPStatusError as exc:
        state = 'restricted' if exc.response.status_code in (401, 403, 429) else 'error'
        return failure(state, f'灯塔接口返回 HTTP {exc.response.status_code}，保留上次成功数据')
    except (httpx.RequestError, ValueError):
        return failure('error', '灯塔接口连接失败或未返回有效JSON，保留上次成功数据')
    if not any(str(r).startswith('SUCCESS::') for r in payload.get('ret', [])):
        return failure('restricted', '灯塔接口未返回成功状态，未更新数值；稍后自动重试')
    rows = board(payload, params['showDate'])
    if rows is None:
        return failure('adapter_pending', '灯塔榜单日期或指标口径不符，未将旧数据当作实时数据')
    readings = {title: parse_payload(payload, title, current=current) for title in DRAMAS}
    evidence = save_evidence(payload, params, current) if any(readings.values()) else None
    result = {}
    for title, values in readings.items():
        for value in values:
            value['source_url'] = evidence
        present = any(isinstance(row, dict) and row.get('mediaName') == title for row in rows)
        result[title] = {'state': 'ok' if values else 'adapter_pending' if present else 'no_data',
            'message': '已自动更新灯塔正片播放量、市占率与排名；每分钟检查，保留平台实际更新时间' if values else
                       '灯塔本剧字段异常或数据已过期，未更新数值' if present else
                       f'灯塔本次返回{len(rows)}条榜单，未包含本剧；不推算播放量或排名',
            'readings': values}
    return result
