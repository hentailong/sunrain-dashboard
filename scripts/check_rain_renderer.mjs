import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../frontend/package.json',import.meta.url));
const {build}=require('esbuild');
const compiled=await build({entryPoints:[new URL('../frontend/src/rain-renderer.ts',import.meta.url).pathname.replace(/^\/(\w:)/,'$1')],bundle:true,write:false,format:'esm',platform:'node'});
const {startRain,rainPauseDelay}=await import('data:text/javascript;base64,'+Buffer.from(compiled.outputFiles[0].text).toString('base64'));
assert.equal(rainPauseDelay(25199),0);
assert.equal(rainPauseDelay(25200),25200);
assert.equal(rainPauseDelay(50399),1);
assert.equal(rainPauseDelay(50400),0);
assert.equal(rainPauseDelay(60000+30000),20400);
let id=0,clears=0,strokes=0;
const frames=new Map(),timers=new Map(),events=new Map();
globalThis.requestAnimationFrame=cb=>{frames.set(++id,cb);return id};
globalThis.cancelAnimationFrame=id=>frames.delete(id);
globalThis.clearTimeout=id=>timers.delete(id);
globalThis.document={hidden:false,addEventListener:(name,cb)=>events.set(name,cb),removeEventListener:name=>events.delete(name)};
globalThis.window={innerWidth:3840,innerHeight:2160,devicePixelRatio:2,setTimeout:(cb,delay)=>{timers.set(++id,{cb,delay});return id},addEventListener:(name,cb)=>events.set(name,cb),removeEventListener:name=>events.delete(name)};
const ctx={clearRect:()=>clears++,stroke:()=>strokes++,setTransform(){},beginPath(){},moveTo(){},lineTo(){}};
const weather={animationName:'sunshower-weather-rain',currentTime:0};
const canvas={clientWidth:3840,clientHeight:2160,getContext:()=>ctx,getAnimations:()=>[weather]};
const cleanup=startRain(canvas);
assert.ok(canvas.width*canvas.height<=2_505_000,'cap the drawing surface on high-DPI displays');
const step=(now,time=now)=>{weather.currentTime=time;const entry=frames.entries().next().value;assert.ok(entry,'one frame should be scheduled');frames.delete(entry[0]);entry[1](now)};
for(let i=0;i<=60;i++)step(i*1000/60);
assert.ok(clears>=28&&clears<=31,`30 fps cap, got ${clears}`);
assert.equal(strokes,clears*3,'batch all drops into three depth passes');
step(2000,25200);
assert.equal(frames.size,0,'no render loop during the clear/rainbow stage');
assert.equal([...timers.values()][0].delay,25200);
document.hidden=true;events.get('visibilitychange')();
assert.equal(timers.size,0);assert.equal(frames.size,0);
document.hidden=false;weather.currentTime=50400;events.get('visibilitychange')();
step(3000,50400);assert.equal(frames.size,1,'resume rain when the tab is visible');
cleanup();assert.equal(frames.size,0);assert.equal(timers.size,0);assert.equal(events.size,0);
console.log('PASS: 30 fps cap, bounded canvas resolution, rain-cycle suspension, hidden-tab pause, resume and cleanup');
